"""Bounded private full-account backup archives.

The archive wraps the portable account-data document and adds chapter bodies
as review-only material. Archive filenames are generated by this service and
are never interpreted as database identifiers or source addresses.
"""
from __future__ import annotations

from datetime import UTC, datetime
from hashlib import sha256
from io import BytesIO
import json
from pathlib import PurePosixPath
import re
import stat
from zipfile import ZIP_DEFLATED, ZipFile, ZipInfo

from fastapi import HTTPException
from sqlalchemy.orm import Session

from app.models import Chapter, ChapterVersion, Library, Novel, User
from app.services import portable_story_service
from app.services.chapter_identity_service import source_version
from app.services.user_data_service import export_user_data, import_user_data
from app.schemas.user_data import UserDataDocument

FORMAT = "nexus-full-backup"
VERSION = 1
MANIFEST = "nexus-backup.json"
MAX_UPLOAD_BYTES = 256 * 1024 * 1024
MAX_UNCOMPRESSED_BYTES = 512 * 1024 * 1024
MAX_ENTRY_BYTES = 32 * 1024 * 1024
MAX_STORY_REVIEW_BYTES = 24 * 1024 * 1024
MAX_ENTRIES = 50_000


def _json_bytes(value: object) -> bytes:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), default=str).encode("utf-8")


def _story_key(library_name: str, url: str | None, identity: dict | None) -> str:
    return sha256(_json_bytes([library_name, url, identity])).hexdigest()


def _safe_source_url(value: str | None) -> str | None:
    """Retain a locator only as private provenance; strip credentials/query."""
    if not value:
        return None
    from urllib.parse import urlsplit, urlunsplit
    try:
        parsed = urlsplit(value)
        if parsed.scheme not in ("http", "https") or not parsed.hostname:
            return None
        host = parsed.hostname.lower()
        if parsed.port:
            host = f"{host}:{parsed.port}"
        return urlunsplit((parsed.scheme.lower(), host, parsed.path, "", ""))[:500]
    except ValueError:
        return None


def _body(chapter: Chapter, *, version: ChapterVersion | None = None) -> dict:
    if version is None:
        return {
            "kind": "current",
            "chapter_key": chapter.chapter_key,
            "manifest_epoch": chapter.manifest_epoch,
            "metadata_manifest_key": chapter.metadata_manifest_key,
            "metadata_chapter_key": chapter.metadata_chapter_key,
            "chapter_number": chapter.chapter_number,
            "title": chapter.title,
            "archived": bool(chapter.archived),
            "category": chapter.category,
            "source_url": _safe_source_url(chapter.source_url),
            "source_version": source_version(chapter),
            "content": chapter.content or "",
            "document": chapter.document,
            "word_count": chapter.word_count,
            "versions": [],
        }
    return {
        "kind": "retained_original",
        "chapter_key": version.chapter_key or chapter.chapter_key,
        "manifest_epoch": chapter.manifest_epoch,
        "metadata_manifest_key": chapter.metadata_manifest_key,
        "metadata_chapter_key": chapter.metadata_chapter_key,
        "chapter_number": chapter.chapter_number,
        "title": version.title or chapter.title,
        "archived": bool(chapter.archived),
        "category": chapter.category,
        "source_url": _safe_source_url(version.source_url),
        "source_version": version.content_version,
        "content": version.content,
        "document": version.document,
        "word_count": chapter.word_count,
        "versions": [],
        "version_reason": version.reason,
    }


def _ensure_reference(story: dict, body: dict) -> str:
    refs = story.setdefault("chapter_refs", [])
    ref = "backup:" + sha256(_json_bytes([
        body["chapter_key"], body["manifest_epoch"], body["source_version"], body["kind"]
    ])).hexdigest()
    reference = {
        "ref": ref,
        "chapter_key": body["chapter_key"],
        "manifest_epoch": body["manifest_epoch"],
        "metadata_manifest_key": body.get("metadata_manifest_key"),
        "metadata_chapter_key": body.get("metadata_chapter_key"),
        "source_version": body["source_version"],
        "chapter_number": body["chapter_number"],
        "title": body.get("title"),
        "archived": body.get("archived", False),
        "source_url": body.get("source_url"),
    }
    existing = next((item for item in refs if item.get("ref") == ref), None)
    if existing is None:
        refs.insert(0,reference)
    elif existing != reference:
        raise HTTPException(500, "Could not create a unique full-backup chapter reference")
    return ref


def export_full_backup(db: Session, user: User, library_name: str | None = None) -> BytesIO:
    document = export_user_data(db, user)
    if library_name is not None:
        if not db.query(Library).filter_by(user_id=user.id,name=library_name).first():
            raise HTTPException(404,"Library not found")
        document["libraries"]=[entry for entry in document["libraries"] if entry["name"]==library_name]
        for shelf in document.get("shelves",[]):
            shelf["novels"]=[member for member in shelf.get("novels",[]) if member.get("library")==library_name]
    stories: dict[str, dict] = {}
    for lib_doc in document["libraries"]:
        for story in lib_doc["novels"]:
            key = _story_key(lib_doc["name"], story.get("url"), story.get("portable_story"))
            stories[key] = story

    files: dict[str, bytes] = {}
    assets = []
    story_asset_bytes: dict[str,int] = {}
    novel_query=db.query(Novel).join(Library, Library.id == Novel.library_id).filter(Library.user_id == user.id)
    if library_name is not None:novel_query=novel_query.filter(Library.name==library_name)
    owned_novels = novel_query.order_by(Library.name, Novel.id).all()
    for novel in owned_novels:
        library = db.get(Library, novel.library_id)
        identity = next((item.get("portable_story") for lib in document["libraries"] if lib["name"] == library.name
                         for item in lib["novels"] if item.get("url") == novel.url), None)
        if novel.url is None:
            identity = portable_story_service.export_identity(db, user, novel)
        story_key = _story_key(library.name, novel.url, identity)
        story = stories.get(story_key)
        if story is None:
            continue
        chapters = db.query(Chapter).execution_options(include_archived_chapters=True).filter_by(
            novel_id=novel.id
        ).order_by(Chapter.chapter_number, Chapter.id).all()
        for chapter in chapters:
            if chapter.content_status.value == "PRESENT" and (chapter.content or chapter.document):
                body = _body(chapter)
                body["versions"] = []
                for version in db.query(ChapterVersion).filter_by(chapter_id=chapter.id).order_by(ChapterVersion.id):
                    saved = _body(chapter, version=version)
                    body["versions"].append({key: value for key, value in saved.items()
                                               if key in ("source_version", "title", "source_url", "content", "document", "version_reason")})
                ref = _ensure_reference(story, body)
                body["reference"] = ref
                path = f"chapters/{story_key}/{sha256(ref.encode()).hexdigest()}.json"
                encoded = _json_bytes(body)
                if len(encoded) > MAX_ENTRY_BYTES:
                    raise HTTPException(413, "One chapter exceeds the 32 MiB per-entry restore limit. That body cannot be included by the current full-backup restore workflow.")
                story_asset_bytes[story_key]=story_asset_bytes.get(story_key,0)+len(encoded)
                if story_asset_bytes[story_key]>MAX_STORY_REVIEW_BYTES:
                    raise HTTPException(413,"This story’s chapter bodies exceed the 24 MiB per-story restore-review limit. Chapter-body backup for this story is unavailable until that limit is raised.")
                files[path] = encoded
                assets.append({"story": story_key, "reference": ref, "path": path,
                               "size": len(encoded), "sha256": sha256(encoded).hexdigest()})
    manifest = {"format": FORMAT, "version": VERSION, "exported_at": datetime.now(UTC).isoformat(),
                "account_data": document, "chapter_assets": assets}
    manifest_bytes = _json_bytes(manifest)
    if len(manifest_bytes) > MAX_ENTRY_BYTES:
        raise HTTPException(413, "The account data index exceeds the full-backup limit.")
    if len(assets)+1>MAX_ENTRIES or sum(len(value) for value in files.values())+len(manifest_bytes)>MAX_UNCOMPRESSED_BYTES:
        raise HTTPException(413,"This backup exceeds the 512 MiB uncompressed archive limit. Export a smaller library or reduce the account’s stored chapter material.")
    output = BytesIO()
    with ZipFile(output, "w", compression=ZIP_DEFLATED, compresslevel=6, allowZip64=True) as archive:
        archive.writestr(MANIFEST, manifest_bytes)
        for path, encoded in files.items():
            archive.writestr(path, encoded)
    output.seek(0)
    if output.getbuffer().nbytes>MAX_UPLOAD_BYTES:
        output.close()
        raise HTTPException(413,"This backup exceeds the 256 MiB compressed archive limit. Export a smaller library or reduce the account’s stored chapter material.")
    return output


def _validate_path(name: str) -> None:
    path = PurePosixPath(name)
    if (not name or "\\" in name or name.startswith("/") or ":" in name or
            any(part in ("", ".", "..") for part in name.split("/")) or path.is_absolute()):
        raise HTTPException(422, "The backup contains an unsafe archive path")


def _read_archive(raw: bytes) -> tuple[UserDataDocument, dict[str, dict[str, dict]]]:
    if len(raw) > MAX_UPLOAD_BYTES:
        raise HTTPException(413, "The backup exceeds the 256 MiB upload limit.")
    try:
        archive = ZipFile(BytesIO(raw), "r")
    except Exception:
        raise HTTPException(422, "That file is not a valid Nexus full backup archive") from None
    with archive:
        infos = archive.infolist()
        if not infos or len(infos) > MAX_ENTRIES:
            raise HTTPException(413, "The backup has too many archive entries")
        names: set[str] = set()
        total = 0
        for info in infos:
            _validate_path(info.filename)
            if info.filename in names:
                raise HTTPException(422, "The backup contains duplicate archive paths")
            names.add(info.filename)
            mode = (info.external_attr >> 16) & 0xFFFF
            if stat.S_ISLNK(mode) or info.flag_bits & 0x1:
                raise HTTPException(422, "The backup contains an unsupported link or encrypted entry")
            if info.file_size > MAX_ENTRY_BYTES:
                raise HTTPException(413, "A backup entry exceeds the 32 MiB limit")
            total += info.file_size
            if total > MAX_UNCOMPRESSED_BYTES:
                raise HTTPException(413, "The backup expands beyond the 512 MiB limit")
        if MANIFEST not in names:
            raise HTTPException(422, "This archive is missing its Nexus backup manifest")
        try:
            manifest = json.loads(archive.read(MANIFEST))
        except Exception:
            raise HTTPException(422, "The backup manifest is invalid JSON") from None
        if not isinstance(manifest, dict) or manifest.get("format") != FORMAT or manifest.get("version") != VERSION:
            raise HTTPException(422, "Unsupported Nexus full backup format or version")
        try:
            document = UserDataDocument.model_validate(manifest["account_data"])
            assets = manifest["chapter_assets"]
            if not isinstance(assets, list) or len(assets) > MAX_ENTRIES:
                raise ValueError
            body_map: dict[str, dict[str, dict]] = {}
            expected = {MANIFEST}
            seen_refs = set()
            for entry in assets:
                if not isinstance(entry, dict):
                    raise ValueError
                story, reference, path = entry["story"], entry["reference"], entry["path"]
                _validate_path(path)
                if path not in names or path == MANIFEST or path in expected:
                    raise ValueError
                expected.add(path)
                key = (story, reference)
                if key in seen_refs:
                    raise ValueError
                seen_refs.add(key)
                encoded = archive.read(path)
                if len(encoded) != entry["size"] or sha256(encoded).hexdigest() != entry["sha256"]:
                    raise ValueError
                body = json.loads(encoded)
                if not isinstance(body, dict) or body.get("reference") != reference:
                    raise ValueError
                if body.get("kind") not in ("current", "retained_original"):
                    raise ValueError
                if not isinstance(body.get("chapter_number"), int) or not isinstance(body.get("content"), str):
                    raise ValueError
                document_version = body.get("document")
                if document_version is not None and not isinstance(document_version, dict):
                    raise ValueError
                if not re.fullmatch(r"[0-9a-f]{64}", str(body.get("source_version", ""))):
                    raise ValueError
                body_map.setdefault(story, {})[reference] = body
            if names != expected:
                raise ValueError
        except HTTPException:
            raise
        except Exception:
            raise HTTPException(422, "The backup manifest or a chapter asset is malformed or has failed integrity checks") from None
    return document, body_map


def import_full_backup(db: Session, user: User, raw: bytes) -> dict:
    if len(raw) > MAX_UPLOAD_BYTES:
        raise HTTPException(413, "The backup exceeds the 256 MiB upload limit.")
    document, body_map = _read_archive(raw)
    # Add body references to the same portable review model used for reading
    # material. No body is copied to Chapter until an explicit reviewed apply.
    story_by_key: dict[str, tuple[str, str | None, dict | None]] = {}
    for library in document.libraries:
        for story in library.novels:
            key = _story_key(library.name, story.url, story.portable_story.model_dump(mode="json") if story.portable_story else None)
            story_by_key[key] = (library.name, story.url, story.portable_story.model_dump(mode="json") if story.portable_story else None)
    for story_key, bodies in body_map.items():
        story_meta = story_by_key.get(story_key)
        if story_meta is None:
            raise HTTPException(422, "A chapter asset refers to an unknown portable story")
        library_name, url, identity = story_meta
        story = next((item for library in document.libraries if library.name == library_name for item in library.novels
                      if item.url == url and (item.portable_story.model_dump(mode="json") if item.portable_story else None) == identity), None)
        if story is None:
            raise HTTPException(422, "A chapter asset refers to an unknown portable story")
        refs = {item.ref for item in story.chapter_refs}
        for reference, body in bodies.items():
            if reference not in refs:
                raise HTTPException(422, "A chapter asset has no matching immutable chapter reference")
    backup_lookup = {
        portable_story_service.reference_key(library_name, url, identity): bodies
        for story_key, bodies in body_map.items()
        for library_name, url, identity in [story_by_key[story_key]]
    }
    # Internal API extension: retains existing JSON import behavior while
    # passing the validated body material to its normal per-story review.
    return import_user_data(db, user, document, private_backup_bodies=backup_lookup)
