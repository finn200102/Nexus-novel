import { test, expect } from "@playwright/test";

test("saved searches retain full catalog criteria and portable imports require similarity review",async({page,request})=>{
  test.skip(process.env.NEXUS_E2E_MODE!=="real","Requires the disposable acceptance stack.");
  await page.goto("/login");
  await page.getByLabel("Username").fill(process.env.NEXUS_E2E_USER!);
  await page.getByLabel("Password").fill(process.env.NEXUS_E2E_PASSWORD!);
  const login=page.waitForResponse(response=>response.url().endsWith("/api/auth/login")&&response.request().method()==="POST");
  await page.getByRole("button",{name:"Sign in",exact:true}).click();
  const headers={Authorization:`Bearer ${(await(await login).json()).access_token}`};
  await expect(page).not.toHaveURL(/\/login/);
  const filters={tag:["Adventure"],crossover:"true",sortBy:"favorites",sortOrder:"desc"};
  await page.goto(`/discover/fanfiction?${new URLSearchParams({q:"Fixture & moon",similar_to:"1",filters:JSON.stringify(filters)})}`);
  await page.getByRole("button",{name:"Save current search",exact:true}).click();
  const dialog=page.getByRole("dialog",{name:"Save search",exact:true});
  await dialog.getByRole("textbox",{name:/Search name/}).fill("Real saved query");
  await dialog.getByRole("button",{name:"Save reviewed search",exact:true}).click();
  await page.getByRole("button",{name:"Open Real saved query",exact:true}).click();
  await expect(page).toHaveURL(url=>url.pathname==="/discover/fanfiction"&&url.searchParams.get("q")==="Fixture & moon"&&url.searchParams.get("similar_to")==="1");
  const response=await request.get("/api/saved-searches",{headers});expect(response.ok()).toBeTruthy();
  expect(response.headers()["cache-control"]).toContain("no-store");
  const saved=(await response.json()).find((row:{name:string})=>row.name==="Real saved query");
  expect(saved.needs_review).toBe(false);expect(saved.definition).toMatchObject({q:"Fixture & moon",site:"fanfiction",similar_to:1,filters});
  await page.getByRole("button",{name:"Edit Real saved query",exact:true}).click();
  const edit=page.getByRole("dialog",{name:"Review saved search",exact:true});
  await edit.getByLabel("Text query",{exact:true}).fill("Revised fixture");
  await edit.getByLabel("Source",{exact:true}).selectOption("royalroad");
  await edit.getByRole("button",{name:"Save reviewed search",exact:true}).click();
  await expect(edit).not.toBeVisible();
  const stale=await request.put(`/api/saved-searches/${saved.id}`,{headers,data:{name:saved.name,definition:saved.definition,expected_revision:saved.revision}});
  expect(stale.status()).toBe(409);expect((await stale.json()).detail.code).toBe("saved_search_changed");
  const portable=await request.get("/api/me/export",{headers});expect(portable.ok()).toBeTruthy();
  const exported=(await portable.json()).saved_searches.find((row:{name:string})=>row.name===saved.name);
  expect(exported.filters).toMatchObject({version:1,q:"Revised fixture",site:"royalroad",similar_to:1,filters});
  const document={format:"nexus-user-export",version:1,libraries:[],saved_searches:[{...exported,name:"Imported query review"}]};
  const imported=await request.post("/api/me/import",{headers,data:document});expect(imported.ok()).toBeTruthy();
  const replay=await request.post("/api/me/import",{headers,data:document});expect(replay.ok()).toBeTruthy();
  expect((await replay.json()).saved_searches).toEqual([{name:"Imported query review",status:"unchanged"}]);
  await page.getByRole("button",{name:"Refresh saved searches",exact:true}).click();
  await expect(page.getByRole("button",{name:"Open Imported query review",exact:true})).toBeDisabled();
  await page.getByRole("button",{name:"Review Imported query review",exact:true}).click();
  await expect(page.getByLabel("Text query",{exact:true})).toHaveValue("Revised fixture");
  await expect(page.getByLabel("Source",{exact:true})).toHaveValue("royalroad");
  await expect(page.getByRole("dialog")).toContainText("another installation");
  await page.getByRole("button",{name:"Cancel",exact:true}).click();
});
