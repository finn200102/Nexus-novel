import {readFileSync} from "node:fs";
import {expect,test} from "@playwright/test";

test("complete library queries and private dynamic shelves retain reviewed rules through portable import",async({page,request})=>{
  test.skip(process.env.NEXUS_E2E_MODE!=="real"||!process.env.NEXUS_E2E_SMART_SHELF_FIXTURE,"Requires the disposable smart-shelf fixture.");
  test.setTimeout(90_000);
  const fixture=JSON.parse(readFileSync(process.env.NEXUS_E2E_SMART_SHELF_FIXTURE!,"utf8"));
  await page.goto("/login");
  await page.getByLabel("Username").fill(process.env.NEXUS_E2E_USER!);
  await page.getByLabel("Password").fill(process.env.NEXUS_E2E_PASSWORD!);
  const login=page.waitForResponse(response=>response.url().endsWith("/api/auth/login")&&response.request().method()==="POST");
  await page.getByRole("button",{name:"Sign in",exact:true}).click();
  const headers={Authorization:`Bearer ${(await(await login).json()).access_token}`};
  await expect(page).not.toHaveURL(/\/login/);
  await page.goto(`/library/${fixture.library_id}`);
  await expect(page.getByText("1–50 of 138 matching stories",{exact:true})).toBeVisible();
  await page.getByRole("button",{name:"Next stories",exact:true}).click();
  await expect(page.getByText("51–100 of 138 matching stories",{exact:true})).toBeVisible();
  await page.getByRole("searchbox",{name:"Search",exact:true}).fill("Late A&B author");
  await expect(page.getByRole("link",{name:"Library fixture 136",exact:true})).toBeVisible();
  await page.getByRole("searchbox",{name:"Search",exact:true}).fill("");
  await page.getByRole("button",{name:"Organize",exact:true}).click();
  await page.getByRole("menuitem",{name:"Smart shelves…",exact:true}).click();
  const sheet=page.getByRole("dialog",{name:"Private smart shelves",exact:true});
  await sheet.getByRole("button",{name:"New smart shelf",exact:true}).click();
  await sheet.getByLabel("Smart shelf name",{exact:true}).fill("Real dynamic shelf");
  await sheet.getByLabel("Libraries to match",{exact:true}).selectOption("all");
  await sheet.getByLabel("Title or author query",{exact:true}).fill("Starlight & moon");
  await sheet.getByLabel("Smart shelf personal tag",{exact:true}).fill("smart-match");
  await sheet.getByLabel("Minimum personal rating",{exact:true}).selectOption("4");
  await sheet.getByLabel("Restrict to static shelf",{exact:true}).selectOption(String(fixture.static_shelf_id));
  await expect(sheet.getByRole("link",{name:"Starlight & moon A",exact:true})).toBeVisible();
  await expect(sheet.getByRole("link",{name:"Starlight & moon B",exact:true})).toHaveAttribute("href",`/library/${fixture.second_library_id}/novels/${fixture.second_match}`);
  await expect(sheet.getByRole("link",{name:"Starlight & moon Foreign",exact:true})).toHaveCount(0);
  await sheet.getByRole("button",{name:"Save reviewed smart shelf",exact:true}).click();
  await expect(sheet.getByText("Smart shelf saved. Results change as your own library changes.",{exact:true})).toBeVisible();
  const saved=await request.get("/api/smart-shelves",{headers});expect(saved.ok()).toBeTruthy();
  const row=(await saved.json()).find((value:{name:string})=>value.name==="Real dynamic shelf");
  expect(row.definition).toMatchObject({scope:"owned_library",library_ids:[],q:"Starlight & moon",user_tag:"smart-match",min_rating:4,shelf_id:fixture.static_shelf_id});
  const personal=await request.put(`/api/personal/novels/${fixture.first_match}`,{headers,data:{user_tags:[]}});expect(personal.ok()).toBeTruthy();
  await sheet.getByRole("button",{name:"Refresh smart shelves",exact:true}).click();
  await expect(sheet.getByRole("link",{name:"Starlight & moon A",exact:true})).toHaveCount(0);
  await expect(sheet.getByRole("link",{name:"Starlight & moon B",exact:true})).toBeVisible();
  const results=await request.post(`/api/smart-shelves/${row.id}/results`,{headers,data:{offset:0,limit:50}});
  expect(results.ok()).toBeTruthy();expect((await results.json()).definition_revision).toBe(row.revision);
  const bound=await request.post("/api/smart-shelves",{headers,data:{name:"Bound private scope",definition:{...row.definition,library_ids:[fixture.library_id,fixture.second_library_id]}}});
  expect(bound.status()).toBe(201);expect((await bound.json()).needs_review).toBe(false);
  const exported=await request.get("/api/me/export",{headers});expect(exported.ok()).toBeTruthy();
  const portable=(await exported.json()).smart_shelves.find((value:{name:string})=>value.name===row.name);
  expect(portable.definition).not.toHaveProperty("library_ids");expect(portable.definition).not.toHaveProperty("shelf_id");
  expect(portable.static_shelf).toBe("Smart fixture references");
  const document={format:"nexus-user-export",version:1,libraries:[],smart_shelves:[{...portable,name:"Imported smart rule review",libraries:["Unavailable library on another installation"]}]};
  const imported=await request.post("/api/me/import",{headers,data:document});expect(imported.ok()).toBeTruthy();
  const replay=await request.post("/api/me/import",{headers,data:document});expect(replay.ok()).toBeTruthy();
  expect((await replay.json()).smart_shelves[0].status).toBe("unchanged");
  await sheet.getByRole("button",{name:"Refresh smart shelves",exact:true}).click();
  await expect(sheet.getByRole("button",{name:"Open Imported smart rule review",exact:true})).toBeDisabled();
  await expect(sheet.getByRole("button",{name:/^Share/})).toHaveCount(0);
});
