import {readFileSync} from "node:fs";
import {test,expect} from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";

test("completed server recordings export a chaptered audiobook and a revocable private feed",async({page,request})=>{
  test.skip(process.env.NEXUS_E2E_MODE!=="real" || !process.env.NEXUS_E2E_COMPANION_FIXTURE,"Requires the disposable acceptance stack.");
  test.setTimeout(180_000);
  const fixture=JSON.parse(readFileSync(process.env.NEXUS_E2E_COMPANION_FIXTURE!,"utf8"));
  await page.goto("/login");
  await page.getByLabel("Username").fill(process.env.NEXUS_E2E_USER!);
  await page.getByLabel("Password").fill(process.env.NEXUS_E2E_PASSWORD!);
  const login=page.waitForResponse(r=>r.url().endsWith("/api/auth/login") && r.request().method()==="POST");
  await page.getByRole("button",{name:"Sign in",exact:true}).click();
  const headers={Authorization:`Bearer ${(await(await login).json()).access_token}`};
  await expect(page).not.toHaveURL(/\/login/);
  const batch=await request.post(`/api/audio/stories/${fixture.novel_id}/jobs`,{headers,data:{chapter_numbers:[1,2],provider:{id:"custom",base_url:"http://fixture-source:8090/tts/v1",model:"fixture",voice:"fixture",language_code:"en",execution_mode:"server"}}});
  expect(batch.status()).toBe(202);
  const jobs=(await batch.json()).outcomes.map((row:{job:{id:number}})=>row.job.id);
  for(const id of jobs)await expect.poll(async()=>{
    const r=await request.get(`/api/audio/jobs/${id}`,{headers});return(await r.json()).status;
  },{timeout:90_000}).toBe("completed");
  await page.goto(`/library/${fixture.library_id}/novels/${fixture.novel_id}?tab=audio`);
  await page.getByText("Audiobook exports and private podcast",{exact:true}).click();
  const section=page.getByRole("region",{name:"Exports and podcast",exact:true});
  await section.getByRole("button",{name:"Select ready recordings on this page",exact:true}).click();
  await expect(section.getByText(/^2 recordings selected for audiobook/)).toBeVisible();
  const queued=page.waitForResponse(r=>r.url().endsWith("/api/audio/exports") && r.request().method()==="POST");
  await section.getByRole("button",{name:"Create M4B audiobook",exact:true}).click();
  const creation=await queued;expect(creation.status()).toBe(202);
  expect(creation.request().postDataJSON().audio_job_ids).toEqual(jobs);
  const exported=await creation.json();
  const downloadButton=section.getByRole("button",{name:`Download audiobook ${exported.id}`,exact:true});
  await expect(downloadButton).toBeVisible({timeout:90_000});
  const download=page.waitForEvent("download");
  await downloadButton.click();
  const file=await download;expect(file.suggestedFilename()).toMatch(/\.m4b$/);
  expect(await file.failure()).toBeNull();
  const ready=await(await request.get(`/api/audio/exports/${exported.id}`,{headers})).json();
  expect(ready.file_ready).toBe(true);expect(ready.audio_bytes).toBeGreaterThan(0);
  expect(ready.chapters).toHaveLength(2);expect(ready.chapters[0].start_seconds).toBe(0);
  expect(ready.chapters[1].start_seconds).toBe(ready.chapters[0].end_seconds);
  const partial=await request.get(`/api/audio/exports/${exported.id}/file`,{headers:{...headers,Range:"bytes=0-31"}});
  expect(partial.status()).toBe(206);expect((await partial.body()).byteLength).toBe(32);

  await section.getByRole("button",{name:"Create private podcast",exact:true}).click();
  const url=await section.getByLabel("Private podcast URL",{exact:true}).inputValue();
  expect(new URL(url).pathname).toMatch(/^\/api\/podcasts\//);
  const feed=await request.get(url);expect(feed.ok()).toBe(true);
  expect(feed.headers()["cache-control"]).toBe("private, no-store");
  await expect.poll(async()=>await(await request.get(url)).text(),{timeout:90_000}).toContain("<enclosure");
  const enclosure=await page.evaluate(async feedUrl=>{
    const xml=new DOMParser().parseFromString(await(await fetch(feedUrl)).text(),"application/xml");
    const item=xml.querySelector("enclosure");return item?{url:item.getAttribute("url"),type:item.getAttribute("type")}:null;
  },url);
  expect(enclosure).toBeTruthy();
  const episode=await request.get(enclosure!.url!,{headers:{Range:"bytes=0-3"}});
  expect(episode.status()).toBe(206);expect((await episode.body()).length).toBe(4);
  expect(episode.headers()["content-type"]).toContain(enclosure!.type!);
  if(enclosure!.type==="audio/wav")expect((await episode.body()).toString()).toBe("RIFF");
  await section.getByRole("button",{name:"Rotate podcast URL",exact:true}).click();
  await page.getByRole("dialog").getByRole("button",{name:"Rotate URL",exact:true}).click();
  await expect(section.getByLabel("Private podcast URL",{exact:true})).not.toHaveValue(url);
  const rotated=await section.getByLabel("Private podcast URL",{exact:true}).inputValue();
  expect((await request.get(url)).status()).toBe(404);
  expect((await request.get(enclosure!.url!)).status()).toBe(404);
  await section.getByRole("button",{name:"Revoke podcast URL",exact:true}).click();
  await page.getByRole("dialog").getByRole("button",{name:"Revoke URL",exact:true}).click();
  await expect(section.getByLabel("Private podcast URL",{exact:true})).toHaveCount(0);
  expect((await request.get(rotated)).status()).toBe(404);
  const accessibility=await new AxeBuilder({page}).withTags(["wcag2a","wcag2aa","wcag21aa"]).analyze();
  expect(accessibility.violations.filter(item=>["serious","critical"].includes(item.impact||""))).toEqual([]);
  await section.getByRole("button",{name:`Delete export ${exported.id}`,exact:true}).click();
  await page.getByRole("dialog").getByRole("button",{name:"Delete audiobook",exact:true}).click();
  await expect(downloadButton).toHaveCount(0);
  for(const id of jobs)expect((await request.get(`/api/audio/jobs/${id}/audio`,{headers})).ok()).toBe(true);
});
