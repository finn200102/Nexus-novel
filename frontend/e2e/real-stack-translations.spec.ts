import { readFileSync } from "node:fs";
import { test, expect } from "@playwright/test";

test("reviewed chapter batches, exact translated EPUBs and explicit passage revision use the isolated provider", async ({ page, request }) => {
  test.skip(process.env.NEXUS_E2E_MODE !== "real" || !process.env.NEXUS_E2E_TRANSLATION_FIXTURE, "Requires the disposable acceptance stack.");
  test.setTimeout(180_000);
  const fixture = JSON.parse(readFileSync(process.env.NEXUS_E2E_TRANSLATION_FIXTURE!, "utf8"));
  const story = `/library/${fixture.library_id}/novels/${fixture.novel_id}`;
  await page.goto("/login");
  await page.getByLabel("Username").fill(process.env.NEXUS_E2E_USER!);
  await page.getByLabel("Password").fill(process.env.NEXUS_E2E_PASSWORD!);
  const login = page.waitForResponse(response => response.url().endsWith("/api/auth/login") && response.request().method() === "POST");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  const headers = { Authorization: `Bearer ${(await (await login).json()).access_token}` };
  await expect(page).not.toHaveURL(/\/login/);
  const trace = async () => (await (await request.get(`http://127.0.0.1:${process.env.NEXUS_FIXTURE_SOURCE_PORT || "8090"}/ai/translation-requests`)).json()).requests;
  const jobsUrl = `/api/reader/stories/${fixture.novel_id}/translations`;
  await page.goto(`${story}?tab=translations`);
  await page.getByText("Translate downloaded chapters", { exact: true }).click();
  const creation = page.getByRole("region", { name: "Create chapter translations", exact: true });
  await creation.getByLabel("Translation provider", { exact: true }).selectOption(String(fixture.provider_id));
  await creation.getByRole("button", { name: "Select downloaded chapters on this page", exact: true }).click();
  await expect(creation.getByText(/^2 chapters selected for translation/)).toBeVisible();
  const preview = page.waitForResponse(response => response.url().endsWith("/translation-batch/preview") && response.request().method() === "POST");
  await creation.getByRole("button", { name: "Review translation batch", exact: true }).click();
  const reviewResponse = await preview;
  expect(reviewResponse.ok()).toBeTruthy();
  const reviewed = await reviewResponse.json();
  expect(reviewed.queueable).toBe(2); expect(reviewed.estimated_max_usd).toBe(0);
  expect(await trace()).toEqual([]);
  const submitted = page.waitForResponse(response => response.url().endsWith("/translation-batch/jobs") && response.request().method() === "POST");
  await creation.getByRole("button", { name: "Queue reviewed translations", exact: true }).click();
  const submission = await submitted; expect(submission.status()).toBe(202);
  const selectedIds = submission.request().postDataJSON().chapter_ids;
  expect(selectedIds).toEqual(fixture.chapters.map((chapter: { id: number }) => chapter.id));
  const queued = await submission.json();
  expect(queued.queued).toBe(2);
  const ids = queued.items.map((item: { job_id: number }) => item.job_id);
  await expect.poll(async () => (await (await request.get(jobsUrl, { headers })).json()).items.map((row: { status: string }) => row.status), { timeout: 90_000 }).toEqual(["completed", "completed"]);
  const replay = await request.post(`/api/reader/stories/${fixture.novel_id}/translation-batch/jobs`, { headers, data: { ...submission.request().postDataJSON(), review_token: reviewed.review_token } });
  expect(replay.status()).toBe(202); expect((await replay.json()).queued).toBe(0);
  expect((await (await request.get(jobsUrl, { headers })).json()).total).toBe(2);
  const panel = page.getByRole("region", { name: "Story translations", exact: true });
  for (let index = 0; index < ids.length; index++) {
    const checkbox = panel.getByRole("checkbox", { name: `Export chapter ${index + 1}, de, variant ${ids[index]}`, exact: true });
    await expect(checkbox).toBeEnabled({ timeout: 15_000 }); await checkbox.check();
  }
  const download = page.waitForEvent("download");
  await panel.getByRole("button", { name: "Download translated EPUB", exact: true }).click();
  const book = await download;
  expect(book.suggestedFilename()).toMatch(/\.epub$/); expect(await book.failure()).toBeNull();
  const bytes = readFileSync((await book.path())!);
  expect(bytes.subarray(0, 2).toString()).toBe("PK");
  expect(bytes.includes(Buffer.from("application/epub+zip"))).toBe(true);
  expect(bytes.includes(Buffer.from("OEBPS/chapter-2.xhtml"))).toBe(true);

  await page.goto(`${story}/1`);
  const block = page.locator(`[data-block-id="${fixture.chapters[0].document.blocks[0].id}"]`);
  await expect(page.locator(".reader__content")).toHaveAttribute("aria-busy", "false");
  const originalHtml = await block.innerHTML(), original = fixture.chapters[0].document.blocks[0].text;
  await block.evaluate(async element => {
    const range = document.createRange(); range.selectNodeContents(element);
    const selection = window.getSelection()!; selection.removeAllRanges(); selection.addRange(range);
    await new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve())));
  });
  await page.getByRole("button", { name: "More reader actions", exact: true }).click();
  await page.getByRole("menuitem", { name: "Translation & story companion", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Translation & story companion", exact: true });
  await dialog.getByLabel("Provider", { exact: true }).selectOption(String(fixture.provider_id));
  await dialog.getByRole("button", { name: "Translate this passage", exact: true }).click();
  await expect(dialog.getByText(`Übersetzung: ${original}`, { exact: true }).and(dialog.locator("p"))).toBeVisible();
  await dialog.getByText("Revise this draft with a chosen provider", { exact: true }).click();
  await dialog.getByLabel("Revision provider", { exact: true }).selectOption(String(fixture.revision_provider_id));
  await dialog.getByLabel("Passage draft to revise", { exact: true }).fill("Reviewed local fixture draft.");
  await dialog.getByRole("button", { name: "Revise reviewed draft", exact: true }).click();
  await expect(dialog.getByText("Überarbeitet: Reviewed local fixture draft.", { exact: true })).toBeVisible();
  expect(await block.innerHTML()).toBe(originalHtml);
  const inputs = await trace();
  expect(inputs).toHaveLength(4);
  expect(inputs.at(-1)).toMatchObject({ model: "fixture-revision", original, draft: "Reviewed local fixture draft.", language: "de" });
  expect(inputs.at(-1)).not.toHaveProperty("evidence");
  const saved = await request.get(`/api/chapter/content/library/${fixture.library_id}/${fixture.novel_id}/1`, { headers });
  expect((await saved.json()).document).toEqual(fixture.chapters[0].document);
  const offlineManifest = await request.get(`/api/reader/stories/${fixture.novel_id}/offline-manifest`, { headers });
  expect(offlineManifest.ok()).toBeTruthy(); expect(offlineManifest.headers()["cache-control"]).toBe("private, no-store");
  const manifest = await offlineManifest.json(); expect(manifest.total).toBe(2);
  expect(manifest.chapters.flatMap((row: { translations: { job_id: number }[] }) => row.translations.map(item => item.job_id)).sort()).toEqual([...ids].sort());
  await page.goto(`${story}?tab=chapters`);
  await page.getByRole("button", { name: "Manage downloads…", exact: true }).click();
  const copies = page.getByRole("dialog", { name: "Downloads and offline", exact: true });
  await copies.getByLabel("Include completed translations", { exact: true }).check();
  await copies.getByRole("button", { name: "Review all downloaded chapters", exact: true }).click();
  await expect(copies.getByRole("region", { name: "Review offline copies", exact: true })).toBeVisible();
  await copies.getByRole("button", { name: "Save reviewed offline copies", exact: true }).click();
  await expect(copies.getByRole("status").filter({ hasText: "Saved 2 chapters offline. 2 translations saved." })).toBeVisible();
  expect(await trace()).toHaveLength(4); // Copying completed media makes no new model request.
});
