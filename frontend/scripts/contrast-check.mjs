#!/usr/bin/env node
// Asserts the WCAG contrast pairs of design-proposal.md §4.1 against src/styles/tokens.css.
// Usage: node scripts/contrast-check.mjs [--write <markdown path>]
// Exit code 1 when any pair is below its threshold (text 4.5:1, UI 3:1, cover titles 7:1).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const css = fs.readFileSync(path.join(here, "../src/styles/tokens.css"), "utf8");

function block(selectorStart) {
  const i = css.indexOf(selectorStart);
  if (i < 0) throw new Error(`selector not found: ${selectorStart}`);
  const open = css.indexOf("{", i);
  const close = css.indexOf("}", open);
  const vars = {};
  for (const m of css.slice(open + 1, close).matchAll(/--([\w-]+):\s*(#[0-9a-fA-F]{6})\b/g)) vars[m[1]] = m[2];
  return vars;
}

function lum(hex) {
  const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const l = c.map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * l[0] + 0.7152 * l[1] + 0.0722 * l[2];
}
export function ratio(a, b) {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
}

const themes = { light: block(":root,\n.nx-theme-light"), dark: block(':root[data-theme="dark"]') };
const TEXT = 4.5;
const UI = 3;
const textFg = ["text", "text-2", "text-muted", "accent", "success", "warning", "danger", "info"];
const surfaces = ["bg", "surface", "surface-2"];
const pairs = [];
for (const fg of textFg) for (const bg of surfaces) pairs.push([fg, bg, TEXT]);
for (const fg of ["border-strong", "focus", "accent-fill"]) for (const bg of surfaces) pairs.push([fg, bg, UI]);
pairs.push(
  ["on-accent", "accent-fill", TEXT],
  ["accent", "accent-subtle", TEXT],
  ["text", "accent-subtle", TEXT],
  ["text-muted", "accent-subtle", TEXT],
  ["on-danger", "danger", TEXT],
  ["on-status", "success", TEXT],
  ["on-status", "warning", TEXT],
  ["on-status", "info", TEXT],
);
for (const s of ["success", "warning", "danger", "info"]) pairs.push([s, `${s}-subtle`, TEXT]);

const rows = [];
let failures = 0;
for (const [name, vars] of Object.entries(themes)) {
  for (const [fg, bg, min] of pairs) {
    if (!vars[fg] || !vars[bg]) throw new Error(`${name}: missing --${fg} or --${bg}`);
    const r = ratio(vars[fg], vars[bg]);
    const ok = r >= min;
    if (!ok) failures++;
    rows.push(`| ${name} | \`--${fg}\` | \`--${bg}\` | ${r.toFixed(2)} | ${min} | ${ok ? "pass" : "**FAIL**"} |`);
  }
}

// Reader themes: text and muted ≥ 4.5, link ≥ 4.5
for (const m of css.matchAll(/\[data-reader-theme="(\w+)"\]\s*\{([^}]*)\}/g)) {
  const v = Object.fromEntries([...m[2].matchAll(/--([\w-]+):\s*(#[0-9a-fA-F]{6})/g)].map((x) => [x[1], x[2]]));
  if (!v["reader-bg"]) continue; // the app-theme scope blocks share the selector
  for (const fg of ["reader-text", "reader-muted", "reader-link"]) {
    const r = ratio(v[fg], v["reader-bg"]);
    const ok = r >= TEXT;
    if (!ok) failures++;
    rows.push(`| reader ${m[1]} | \`--${fg}\` | \`--reader-bg\` | ${r.toFixed(2)} | ${TEXT} | ${ok ? "pass" : "**FAIL**"} |`);
  }
  // Reader bars (WP-D5) carry reader text and muted text on --reader-bar.
  for (const fg of ["reader-text", "reader-muted"]) {
    if (!v["reader-bar"]) continue;
    const r = ratio(v[fg], v["reader-bar"]);
    const ok = r >= TEXT;
    if (!ok) failures++;
    rows.push(`| reader ${m[1]} | \`--${fg}\` | \`--reader-bar\` | ${r.toFixed(2)} | ${TEXT} | ${ok ? "pass" : "**FAIL**"} |`);
  }
}

// Cover fallback hues: white title ≥ 7
for (const m of css.matchAll(/--(cover-\d):\s*(#[0-9a-fA-F]{6})/g)) {
  const r = ratio("#ffffff", m[2]);
  const ok = r >= 7;
  if (!ok) failures++;
  rows.push(`| cover | \`#ffffff\` | \`--${m[1]}\` | ${r.toFixed(2)} | 7 | ${ok ? "pass" : "**FAIL**"} |`);
}

const md = [
  "# Token contrast report",
  "",
  "Generated by `nexus-novel/frontend/scripts/contrast-check.mjs` from `src/styles/tokens.css` (`npm run check:contrast`). Do not edit by hand.",
  "",
  "| Theme | Foreground | Background | Ratio | Minimum | Result |",
  "|---|---|---|---|---|---|",
  ...rows,
  "",
  `${rows.length} pairs, ${failures} failures.`,
  "",
].join("\n");

const w = process.argv.indexOf("--write");
if (w > 0) fs.writeFileSync(process.argv[w + 1], md);
console.log(`contrast-check: ${rows.length} pairs, ${failures} failures`);
if (failures) {
  console.log(rows.filter((r) => r.includes("FAIL")).join("\n"));
  process.exit(1);
}
